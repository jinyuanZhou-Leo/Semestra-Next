// Generates the changelog pages (content/docs/changelog{,.zh}.mdx, not committed) from
// release-notes/*.json at the repository root, which `pnpm release:version` writes. Runs before
// `dev` and `build`.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

type Kind = 'breaking' | 'new' | 'improved' | 'fixed'
type Release = {
  version: string
  date: string
  items: { kind: Kind; en: string; zh: string }[]
}

const notesDir = path.resolve(import.meta.dirname, '../../../release-notes')
const output = path.resolve(import.meta.dirname, '../content/docs')

const kinds: Kind[] = ['breaking', 'new', 'improved', 'fixed']
const text = {
  en: {
    title: 'Changelog',
    description: 'What changed in each version of Semestra.',
    empty: 'No versions have been released yet.',
    kinds: { breaking: 'Needs your attention', new: 'New', improved: 'Improved', fixed: 'Fixed' },
  },
  zh: {
    title: '更新日志',
    description: 'Semestra 每个版本的变化。',
    empty: '还没有发布过版本。',
    kinds: { breaking: '需要你留意', new: '新功能', improved: '改进', fixed: '修复' },
  },
} as const

function compareVersions(a: string, b: string): number {
  const pa = a.split(/[.-]/, 3).map(Number)
  const pb = b.split(/[.-]/, 3).map(Number)
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return (pa[i] ?? 0) - (pb[i] ?? 0)
  return 0
}

/** Release notes are plain text; keep MDX from reading braces and angle brackets as code. */
function escapeMdx(value: string): string {
  return value.replace(/[{}<>]/g, (c) => `\\${c}`)
}

const files = (await readdir(notesDir)).filter((name) => name.endsWith('.json'))
const releases = (
  await Promise.all(
    files.map(
      async (name) => JSON.parse(await readFile(path.join(notesDir, name), 'utf8')) as Release,
    ),
  )
).toSorted((a, b) => compareVersions(b.version, a.version))

for (const lang of ['en', 'zh'] as const) {
  const t = text[lang]
  const sections = releases.map((release) => {
    const groups = kinds
      .map((kind) => {
        const items = release.items.filter((item) => item.kind === kind)
        if (items.length === 0) return ''
        return `### ${t.kinds[kind]}\n\n${items.map((item) => `- ${escapeMdx(item[lang])}`).join('\n')}\n`
      })
      .filter(Boolean)
    return `## ${release.version}\n\n${release.date}\n\n${groups.join('\n')}`
  })
  const body = sections.length > 0 ? sections.join('\n') : `${t.empty}\n`
  const page = `---\ntitle: ${t.title}\ndescription: ${t.description}\n---\n\n{/* Generated by scripts/generate-changelog.ts from release-notes/*.json; do not edit. */}\n\n${body}`
  await writeFile(path.join(output, lang === 'en' ? 'changelog.mdx' : 'changelog.zh.mdx'), page)
}
