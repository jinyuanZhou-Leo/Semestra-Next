// Writes `src/lib/message-groups/*.gen.ts`: the messages that code looks up by a computed key
// (`error_<code>`, `settings_<namespace>_<field>_label`, ...), one file per group.
//
// Looking a key up on the whole `messages` namespace keeps all ~2 400 messages in the first
// bundle, because the bundler cannot tell which ones are used. A group file names its keys, so
// only that group is bundled, and only with the code that needs it.
//
// `node scripts/gen-message-groups.mjs` rewrites the files; `--check` fails when they are stale
// (run by `pnpm i18n:lint`).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

const GROUPS = [
  { file: 'errors', name: 'errorMessages', prefix: 'error_' },
  { file: 'settings', name: 'settingsMessages', prefix: 'settings_' },
  { file: 'capabilities', name: 'capabilityMessages', prefix: 'capability_' },
  { file: 'assistant-fields', name: 'assistantFieldMessages', prefix: 'assistant_field_' },
  { file: 'job-steps', name: 'jobStepMessages', prefix: 'job_step_' },
  {
    file: 'portability-entities',
    name: 'portabilityEntityMessages',
    prefix: 'portability_entity_',
  },
]

const messagesFile = new URL('../messages/en.json', import.meta.url)
const outDir = new URL('../src/lib/message-groups/', import.meta.url)
const keys = Object.keys(JSON.parse(readFileSync(messagesFile, 'utf8')))
  .filter((key) => !key.startsWith('$'))
  .toSorted()

function render({ name, prefix }) {
  const entries = keys.filter((key) => key.startsWith(prefix)).map((key) => `  ${key}: m.${key},`)
  return [
    `// Generated by scripts/gen-message-groups.mjs from messages/en.json. Do not edit.`,
    `import { m } from '@/paraglide/messages'`,
    ``,
    `type MessageFn = (params?: Record<string, unknown>) => string`,
    ``,
    `/** Messages whose key starts with \`${prefix}\`, for lookups by a computed key. */`,
    `export const ${name} = {`,
    ...entries,
    `} as unknown as Readonly<Record<string, MessageFn | undefined>>`,
    ``,
  ].join('\n')
}

const check = process.argv.includes('--check')
const stale = []
mkdirSync(outDir, { recursive: true })
for (const group of GROUPS) {
  const target = new URL(`${group.file}.gen.ts`, outDir)
  const content = render(group)
  let current = null
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing
  }
  if (current === content) continue
  if (check) stale.push(`src/lib/message-groups/${group.file}.gen.ts`)
  else writeFileSync(target, content)
}
// Every lookup by a computed key goes through a group above; one on the whole namespace would
// pull every message into the bundle again.
const src = new URL('../src/', import.meta.url)
const NAMESPACE_LOOKUP = [/import \* as \w+ from '@\/paraglide\/messages'/, /(?<![\w.])m\[/]
const lookups = []
for (const entry of readdirSync(src, { recursive: true })) {
  const file = String(entry)
  if (
    !/\.tsx?$/.test(file) ||
    file.startsWith('paraglide/') ||
    file.startsWith('lib/message-groups/')
  )
    continue
  const lines = readFileSync(new URL(file, src), 'utf8').split('\n')
  lines.forEach((line, index) => {
    if (NAMESPACE_LOOKUP.some((pattern) => pattern.test(line)))
      lookups.push(`src/${file}:${index + 1}`)
  })
}
if (lookups.length) {
  console.error(
    `Look messages up by a computed key through src/lib/message-groups: ${lookups.join(', ')}`,
  )
  process.exit(1)
}
if (stale.length) {
  console.error(`Stale, run \`pnpm i18n:groups\`: ${stale.join(', ')}`)
  process.exit(1)
}
